/* ---------------- CCTP V2 USDC bridge (stateless, holds no funds) ---------------- */
function bridgeV2Source(name, net){
  return `// SPDX-License-Identifier: MIT
pragma solidity ^0.8.24;

interface IERC20 {
    function transferFrom(address from, address to, uint256 amount) external returns (bool);
    function approve(address spender, uint256 amount) external returns (bool);
}

/// @dev Circle CCTP V2 TokenMessenger (subset)
interface ITokenMessengerV2 {
    function depositForBurn(
        uint256 amount,
        uint32 destinationDomain,
        bytes32 mintRecipient,
        address burnToken,
        bytes32 destinationCaller,
        uint256 maxFee,
        uint32 minFinalityThreshold
    ) external;
}

/// @dev Circle CCTP V2 MessageTransmitter (subset)
interface IMessageTransmitterV2 {
    function localDomain() external view returns (uint32);
}

/// @title ${name} — USDC bridge to other chains through Circle CCTP V2
/// @notice Generated by ContractForge for ${net.label} (chainId ${net.chainIdDec}). Deploy the same source on every chain.
/// @dev Burns USDC here and mints it to \`recipient\` on the destination chain. The mint on the destination
///      is completed by anyone calling receiveMessage on that chain's MessageTransmitter with Circle's
///      attestation (the recipient or any relayer can do it). This contract keeps no balance and has no owner.
///      Domains: Ethereum 0, Avalanche 1, OP 2, Arbitrum 3, Base 6, Polygon 7, Arc 26.
///      minFinalityThreshold: 1000 = Fast Transfer (a fee up to maxFee applies), 2000 = Standard (maxFee can be 0).
contract ${name} {
    ITokenMessengerV2 public immutable tokenMessenger;
    IMessageTransmitterV2 public immutable messageTransmitter;
    IERC20 public immutable usdc;
    uint32 public immutable localDomain;

    event BridgeInitiated(
        address indexed sender,
        address indexed recipient,
        uint32 destinationDomain,
        uint256 amount,
        uint256 maxFee,
        uint32 minFinalityThreshold
    );

    constructor(address tokenMessenger_, address messageTransmitter_, address usdc_) {
        require(
            tokenMessenger_.code.length > 0 && messageTransmitter_.code.length > 0 && usdc_.code.length > 0,
            "not a contract"
        );
        tokenMessenger = ITokenMessengerV2(tokenMessenger_);
        messageTransmitter = IMessageTransmitterV2(messageTransmitter_);
        usdc = IERC20(usdc_);
        localDomain = IMessageTransmitterV2(messageTransmitter_).localDomain();
    }

    /// @notice Bridge \`amount\` of the caller's USDC (approve this contract first) to \`recipient\` on another chain.
    function bridgeUSDC(
        uint256 amount,
        uint32 destinationDomain,
        address recipient,
        uint256 maxFee,
        uint32 minFinalityThreshold
    ) external {
        require(amount > 0, "zero amount");
        require(recipient != address(0), "zero recipient");
        require(destinationDomain != localDomain, "same chain");
        require(maxFee < amount, "fee too high");

        _call(address(usdc), abi.encodeCall(IERC20.transferFrom, (msg.sender, address(this), amount)));
        _call(address(usdc), abi.encodeCall(IERC20.approve, (address(tokenMessenger), amount)));

        emit BridgeInitiated(msg.sender, recipient, destinationDomain, amount, maxFee, minFinalityThreshold);
        tokenMessenger.depositForBurn(
            amount,
            destinationDomain,
            bytes32(uint256(uint160(recipient))),
            address(usdc),
            bytes32(0), // anyone may complete the mint on the destination chain
            maxFee,
            minFinalityThreshold
        );
    }

    function _call(address token, bytes memory data) private {
        (bool ok, bytes memory ret) = token.call(data);
        require(ok && (ret.length == 0 || abi.decode(ret, (bool))), "token call failed");
    }
}`;
}

function bridgeCtorArgs(userSet){
  const f = userSet || {};
  return [
    { param:'tokenMessenger_',    type:'address', hint:'tokenMessenger',    value: f.tokenMessenger || '',    userSet: !!f.tokenMessenger,    genNetwork: activeNetwork },
    { param:'messageTransmitter_', type:'address', hint:'messageTransmitter', value: f.messageTransmitter || '', userSet: !!f.messageTransmitter, genNetwork: activeNetwork },
    { param:'usdc_',              type:'address', hint:'usdc',              value: f.usdc || '',              userSet: !!f.usdc,              genNetwork: activeNetwork }
  ];
}

/* Section 06 in a multichain mode: the V2 bridge (the V1 form below it is unchanged in single mode). */
function genCrosschainV2(){
  const net = NETWORKS[activeNetwork];
  const name = (document.getElementById('cc_name').value || 'ArcCrossPay').replace(/[^A-Za-z0-9]/g, '');
  const val = (id) => (document.getElementById(id)?.value || '').trim();
  const code = bridgeV2Source(name, net);
  pendingCtorArgs = bridgeCtorArgs({ tokenMessenger: val('cc_tokenmessenger'), messageTransmitter: val('cc_msgtransmitter'), usdc: val('cc_usdc') });
  showCode('crosschainCode', name + '.sol', code);
  pendingSource = { name, code };
  document.getElementById('pendingContractLabel').value = name + '.sol  (' + net.label + ')';
  renderCtorArgs();
  if(!cctpV2(activeNetwork)) logConsole('warn', net.label + ' has no CCTP V2 deployment in this app. Enter the TokenMessenger and MessageTransmitter addresses before deploying.');
}

/* ---------------- Multi-deploy ---------------- */
const mdState = { selected: new Set(), includeBridge: false, running: false, edits: {} };

function mdVisible(){ return multichainMode === 'multi' || multichainMode === 'cross'; }

function mdNetworks(){
  const testnets = Object.entries(NETWORKS).filter(([, n]) => !n.isMainnet);
  const mainnets = Object.entries(NETWORKS).filter(([, n]) => n.isMainnet);
  return { testnets, mainnets };
}

function mdArgsFor(args, netKey){
  return args.map(a => ({ ...a, shown: ctorArgValue(a, netKey) }));
}

function mdEdit(id, value){ mdState.edits[id] = value; }

function mdSetRunning(on){
  mdState.running = on;
  const b = document.getElementById('mdDeployBtn');
  if(b){ b.disabled = on; b.textContent = on ? 'Deploying…' : b.dataset.label || b.textContent; }
}

function toggleMdNetwork(key){
  if(mdState.selected.has(key)) mdState.selected.delete(key); else mdState.selected.add(key);
  renderMultiDeployPanel();
}

function toggleMdBridge(on){ mdState.includeBridge = !!on; renderMultiDeployPanel(); }

function renderMultiDeployPanel(){
  const box = document.getElementById('multiDeployPanel');
  if(!box) return;
  if(!mdVisible()){ box.style.display = 'none'; box.innerHTML = ''; return; }
  const hasSource = !!(pendingSource && pendingSource.code);
  if(hasSource) syncCtorArgsFromSource();
  const { testnets, mainnets } = mdNetworks();
  const chip = ([key, n]) => '<label class="md-chip'+(mdState.selected.has(key)?' on':'')+'"><input type="checkbox" '+(mdState.selected.has(key)?'checked ':'')+'onchange="toggleMdNetwork(\''+key+'\')" /> '+escapeHtml(n.label)+(n.isMainnet?' <span class="md-live">LIVE</span>':'')+'</label>';
  let html = '<div class="mc-title">Deploy to several networks <span>'+MC_MODES[multichainMode].label+' mode</span></div>'
    + '<div class="md-group"><div class="md-group-label">Testnets</div>'+testnets.map(chip).join('')+'</div>'
    + '<div class="md-group"><div class="md-group-label">Mainnets (real funds)</div>'+mainnets.map(chip).join('')+'</div>';
  if(multichainMode === 'cross'){
    html += '<label class="md-bridge"><input type="checkbox" '+(mdState.includeBridge?'checked ':'')+'onchange="toggleMdBridge(this.checked)" /> Also deploy a CCTP V2 USDC bridge on each chain that supports it</label>';
  }
  const sel = [...mdState.selected].filter(k => NETWORKS[k]);
  if(hasSource && sel.length && pendingCtorArgs.length){
    html += '<div class="md-table-wrap"><table class="md-table"><thead><tr><th>Network</th>'
      + pendingCtorArgs.map(a => '<th>'+escapeHtml(a.param.replace(/_$/, ''))+'</th>').join('')+'</tr></thead><tbody>'
      + sel.map(k => '<tr><td>'+escapeHtml(NETWORKS[k].label)+'</td>'
        + pendingCtorArgs.map((a, i) => { const id = 'md_'+k+'_'+i; const v = (id in mdState.edits) ? mdState.edits[id] : ctorArgValue(a, k); return '<td><input id="'+id+'" value="'+escapeHtml(v)+'" placeholder="'+(v?'':'required')+'" class="'+(v?'':'md-missing')+'" oninput="mdEdit(this.id,this.value)" /></td>'; }).join('')
        + '</tr>').join('')
      + '</tbody></table></div>';
  }
  html += '<div class="btnrow"><button class="btn btn-primary" id="mdDeployBtn" data-label="Deploy to '+sel.length+' network'+(sel.length===1?'':'s')+'" onclick="multiDeploy()" '+(mdState.running?'disabled':'')+'>'+(mdState.running?'Deploying…':'Deploy to '+sel.length+' network'+(sel.length===1?'':'s'))+'</button></div>'
    + '<div class="hint">Compiles once, then for each network: switches your wallet, fills that network\'s addresses, and deploys. Each network asks for your confirmation in the wallet.</div>';
  box.style.display = 'block';
  box.innerHTML = html;
}

function mdRowValues(key, abiInputs){
  return abiInputs.map((inp, i) => {
    const el = document.getElementById('md_'+key+'_'+i);
    return coerceCtorValue(inp.type, el ? el.value : '', (inp.name || ('argument '+(i+1)))+' on '+NETWORKS[key].label);
  });
}

async function mdWaitForChain(key){
  const want = NETWORKS[key].chainIdDec;
  for(let i = 0; i < 10; i++){
    provider = new ethers.providers.Web3Provider(window.ethereum, 'any');
    signer = provider.getSigner();
    const net = await provider.getNetwork();
    if(net.chainId === want) return true;
    await new Promise(r => setTimeout(r, 400));
  }
  return false;
}

async function multiDeploy(){
  if(mdState.running) return;
  if(!pendingSource.code){ logConsole('err','Generate a contract first.'); return; }
  if(!signer || !account){ logConsole('err','Connect your wallet first.'); return; }
  const keys = [...mdState.selected].filter(k => NETWORKS[k]);
  if(!keys.length){ logConsole('err','Select at least one network.'); return; }
  if(/0x0{34,36}dEaD/i.test(pendingSource.code) && keys.some(k => NETWORKS[k].isMainnet)){
    logConsole('err','Mainnet deploy blocked: the contract contains the placeholder address 0x…dEaD. Replace it with a real address and generate again.');
    return;
  }

  mdSetRunning(true);
  const original = activeNetwork;
  const results = [];
  try{
    logConsole('warn','Multi-deploy: compiling '+pendingSource.name+'.sol once…');
    const main = await compilePending();
    const mainInputs = (main.abi.find(x => x.type === 'constructor') || { inputs: [] }).inputs;
    let bridge = null, bridgeInputs = [];
    const wantBridge = multichainMode === 'cross' && mdState.includeBridge;
    if(wantBridge){
      const bname = pendingSource.name + 'Bridge';
      bridge = await compileSource(bname, bridgeV2Source(bname, NETWORKS[original]));
      bridgeInputs = (bridge.abi.find(x => x.type === 'constructor') || { inputs: [] }).inputs;
    }

    for(const key of keys){
      const net = NETWORKS[key];
      try{
        activeNetwork = key; renderNetBar(); updateSideNet();
        logConsole('warn','— '+net.label+' —');
        if(net.isMainnet && !mainnetDeployConfirm()){ logConsole('warn','Skipped '+net.label+' (mainnet deployment cancelled).'); results.push([net.label,'skipped']); continue; }
        await switchWalletNetwork();
        if(!(await mdWaitForChain(key))){ throw new Error('wallet did not switch to '+net.label+' (chainId '+net.chainIdDec+')'); }
        const values = mdRowValues(key, mainInputs);
        const c = await deployCompiled(main, values, key);
        results.push([net.label, c.address]);
        if(bridge){
          const cc = cctpV2(key);
          if(!cc){ logConsole('warn','No CCTP V2 on '+net.label+', bridge skipped.'); results.push([net.label+' bridge','skipped']); }
          else {
            const bvals = [cc.tokenMessenger, cc.messageTransmitter, net.usdc];
            if(bvals.some(v => !v)) { logConsole('warn','Missing USDC address on '+net.label+', bridge skipped.'); results.push([net.label+' bridge','skipped']); }
            else {
              const b = await deployCompiled({ ...bridge, name: pendingSource.name+'Bridge' }, bvals.map((v,i)=>coerceCtorValue(bridgeInputs[i].type, v, bridgeInputs[i].name)), key);
              results.push([net.label+' bridge', b.address]);
            }
          }
        }
      }catch(e){
        logConsole('err', net.label+': '+(e.message || e));
        results.push([net.label, 'failed']);
      }
    }
  }catch(e){
    logConsole('err','Multi-deploy stopped: '+(e.message || e));
  }finally{
    activeNetwork = original; renderNetBar(); updateSideNet();
    try{ if(account) await switchWalletNetwork(); }catch(_){ /* ignore */ }
    mdSetRunning(false);
  }
  logConsole('ok','Multi-deploy finished: '+results.map(r => r[0]+' → '+r[1]).join(' · '));
  return results;
}

