// Proves that the Slither triage is pinned to the code: changing a triaged function makes the check fail and name the entry;
// changing only the stamp, a comment or whitespace does not; `--rehash` writes nothing without --confirm and only touches one entry.
// Needs slither and solc 0.8.24 (set SOLC to use another binary). Run by the slither job; exits 0 with a notice when slither is missing
// unless REQUIRE_SLITHER=1.
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(here, '..');
let pass = 0, fail = 0;
const ok = (c, m, d) => { if (c) pass++; else { fail++; console.log('FAIL', m, d || ''); } };

if (spawnSync('slither', ['--version']).status !== 0) {
  const msg = 'slither not found: the triage pin tests were skipped';
  if (process.env.REQUIRE_SLITHER === '1') { console.error('FAIL: ' + msg + ' (REQUIRE_SLITHER=1)'); process.exit(1); }
  console.log(msg); process.exit(0);
}
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'pin-'));
const golden = fs.readFileSync(path.join(here, 'golden/arcMain/simple-escrow.sol'), 'utf8');
const run = (name, text, extra = []) => {
  const f = path.join(tmp, name + '.sol'); fs.writeFileSync(f, text);
  const r = spawnSync('node', ['slither-check.mjs', '--files', f, '--out', path.join(tmp, 'out-' + name), ...extra], { cwd: here, encoding: 'utf8', env: process.env });
  return { code: r.status, out: (r.stdout || '') + (r.stderr || '') };
};
const FUND_CHECK = 'require(msg.sender == buyer, "only buyer");';
ok(golden.includes(FUND_CHECK), 'the escrow golden has the check the pin test edits');

const base = run('base', golden);
ok(base.code === 0, 'unchanged code: the triaged finding is covered', base.out.slice(-400));

const stamp = run('stamp', golden.replace(/^\/\/ ContractForge v\S+ \| maturity: \w+ \| NOT AUDITED$/m, '// ContractForge v9.9.9 | maturity: experimental | NOT AUDITED').replace(/Generated by ContractForge for .*/, 'Generated by ContractForge for Somewhere Else (chainId 1)'));
ok(stamp.code === 0, 'only the stamp and the network label changed: still covered', stamp.out.slice(-400));

const cmt = run('comment', golden.replace(FUND_CHECK, FUND_CHECK + '   // a new comment   \n        /* and another */'));
ok(cmt.code === 0, 'a comment and whitespace inside the function: still covered', cmt.out.slice(-400));

const edited = run('edited', golden.replace(FUND_CHECK, 'require(msg.sender != address(0), "only buyer");'));
ok(edited.code === 1, 'the triaged function changed: the check fails', edited.out.slice(-500));
ok(/arbitrary-send-erc20@ArcEscrow\.fund/.test(edited.out) && /--rehash/.test(edited.out) && /the code changed|code behind these triage entries changed/.test(edited.out), 'the failure names the entry and the re-pin command', edited.out.slice(-500));

// another function changed, the triaged one did not: the pin of fund() is untouched
const other = run('other', golden.replace('function release()', 'uint256 public pinProbe;\n    function release()'));
ok(!/arbitrary-send-erc20@ArcEscrow\.fund/.test(other.out.replace(/node slither-check[^\n]*/g, '')) || other.code === 0, 'a change outside the triaged function does not break its pin', other.out.slice(-300));

// --rehash: dry run writes nothing, unknown ids and "all" are refused, one entry at a time
const triageFile = path.join(repo, '.github/slither-triage.json');
const before = fs.readFileSync(triageFile, 'utf8');
const dry = spawnSync('node', ['slither-check.mjs', '--files', path.join(tmp, 'edited.sol'), '--out', path.join(tmp, 'out-dry'), '--rehash', 'arbitrary-send-erc20@ArcEscrow.fund'], { cwd: here, encoding: 'utf8' });
ok(dry.status === 0 && /Nothing was written/.test(dry.stdout) && /reason    :/.test(dry.stdout) && /^\+/m.test(dry.stdout), 'rehash without --confirm shows the reason and the difference and writes nothing', dry.stdout.slice(-400));
ok(fs.readFileSync(triageFile, 'utf8') === before, 'the triage file is untouched after the dry run');
for (const bad of ['all', '*', 'no-such-entry']) {
  const r = spawnSync('node', ['slither-check.mjs', '--files', path.join(tmp, 'base.sol'), '--out', path.join(tmp, 'out-bad'), '--rehash', bad, '--confirm'], { cwd: here, encoding: 'utf8' });
  ok(r.status === 2 && fs.readFileSync(triageFile, 'utf8') === before, `rehash '${bad}' is refused and nothing changes`, r.stderr.slice(0, 200));
}
// every entry in the file carries a pin and a snapshot
const t = JSON.parse(before);
ok(t.entries.length > 0 && t.entries.every((e) => e.hash && e.function), 'every triage entry has a function and a hash');
ok(t.entries.every((e) => fs.existsSync(path.join(repo, '.github/slither-snapshots', ((e.id || e.detector + '@' + e.contract + '.' + e.function)).replace(/[^A-Za-z0-9_.@-]/g, '_') + '.txt'))), 'every triage entry has a snapshot');

fs.rmSync(tmp, { recursive: true, force: true });
console.log(pass + ' passed, ' + fail + ' failed');
process.exit(fail ? 1 : 0);
