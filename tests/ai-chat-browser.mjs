// Phase 8: the AI -> Solidity chat in a real browser (Chromium through playwright), under the page's real policy.
// Checks layout at desktop, tablet and phone widths: no sideways page scroll, the composer stays inside the screen,
// code blocks scroll on their own, the history drawer opens and closes. Set SHOTS=/some/dir to also save screenshots.
// Without a usable browser it prints a notice and exits 0, unless REQUIRE_BROWSER=1 (same rule as csp-browser.mjs).
import http from 'node:http';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const dir = path.resolve(here, '../contractforge-deploy');
let pass = 0, fail = 0;
const ok = (c, m, d) => { if (c) pass++; else { fail++; console.log('FAIL', m, d || ''); } };
const skip = (why) => { if (process.env.REQUIRE_BROWSER === '1') { console.error('FAIL: ' + why + ' (REQUIRE_BROWSER=1)'); process.exit(1); } console.log('NOT tested in a real browser: ' + why); process.exit(0); };

let chromium;
try { ({ chromium } = await import('playwright')); } catch (_) { skip('playwright is not installed'); }

const headers = {};
{
  let cur = false;
  for (const l of fs.readFileSync(path.join(dir, '_headers'), 'utf8').split('\n')) {
    if (l.startsWith('/')) { cur = l.trim() === '/*'; continue; }
    const m = l.match(/^\s+([A-Za-z-]+):\s*(.*)$/); if (cur && m) headers[m[1]] = m[2];
  }
}
const types = { '.html': 'text/html', '.js': 'text/javascript', '.css': 'text/css', '.svg': 'image/svg+xml', '.json': 'application/json' };
const server = http.createServer((req, res) => {
  const u = req.url.split('?')[0]; const f = path.join(dir, u === '/' ? 'index.html' : u);
  if (!f.startsWith(dir) || !fs.existsSync(f) || fs.statSync(f).isDirectory()) { res.writeHead(404); res.end(); return; }
  res.writeHead(200, { ...headers, 'Content-Type': types[path.extname(f)] || 'application/octet-stream', 'Cache-Control': 'no-store' });
  res.end(fs.readFileSync(f));
});
await new Promise((r) => server.listen(0, '127.0.0.1', r));
const origin = 'http://127.0.0.1:' + server.address().port;

let browser;
try { browser = await chromium.launch(process.env.CHROME ? { executablePath: process.env.CHROME } : {}); } catch (e) { server.close(); skip('no Chromium could be started (' + String(e.message).split('\n')[0] + ')'); }

const LONG = Array.from({ length: 60 }, (_, i) => `    uint256 public value${i}; // ${'a very long comment to force sideways scrolling '.repeat(4)}`).join('\n');
const REPLY = '## Plan\nHere is a **vault**:\n\n```solidity\n// Generated by ContractForge AI for Arc\npragma solidity ^0.8.24;\ncontract ArcVault {\n' + LONG + '\n}\n```\n\n- one\n- two';
const CONVS = Array.from({ length: 6 }, (_, i) => ({ id: 'c' + i, msgs: [{ role: 'user', content: 'Conversation number ' + i + ' about a long title that should be truncated nicely in the list' }, { role: 'assistant', content: i === 0 ? REPLY : 'ok ' + i }] }));

for (const [name, vp] of [['desktop', { width: 1366, height: 800 }], ['tablet', { width: 900, height: 1000 }], ['phone', { width: 390, height: 780 }]]) {
  const ctx = await browser.newContext({ viewport: vp, hasTouch: name === 'phone', isMobile: name === 'phone' });
  const page = await ctx.newPage();
  const problems = [];
  page.on('console', (m) => { if (m.type() === 'error') problems.push(m.text()); });
  page.on('pageerror', (e) => problems.push(String(e)));
  await page.addInitScript(([k, v]) => { try { if (!localStorage.getItem(k)) localStorage.setItem(k, v); } catch (_) {} }, ['cf_ai_chats_v1', JSON.stringify(CONVS)]);
  await page.goto(origin + '/');
  await page.evaluate(() => document.querySelector('.nav-item[data-section="nlai"]').click());
  await page.waitForSelector('#aiThread .ai-code-block');
  await page.evaluate(() => document.getElementById('aiChat').scrollIntoView({ block: 'start' }));
  const m = await page.evaluate(() => {
    const r = (el) => { const b = el.getBoundingClientRect(); return { l: b.left, r: b.right, t: b.top, b: b.bottom, w: b.width, h: b.height }; };
    const code = document.querySelector('#aiThread .ai-code'), chat = document.getElementById('aiChat'), comp = document.getElementById('aiComposer'), send = document.getElementById('aiSendBtn');
    const side = document.getElementById('aiSidebar');
    return {
      docOverflow: document.documentElement.scrollWidth - document.documentElement.clientWidth,
      chat: r(chat), comp: r(comp), send: r(send), side: r(side), sideVisible: getComputedStyle(side).visibility,
      codeScrollsX: code.scrollWidth > code.clientWidth, codeWidth: code.getBoundingClientRect().width, threadW: document.getElementById('aiThread').clientWidth,
      threadScrolls: document.getElementById('aiThread').scrollHeight > document.getElementById('aiThread').clientHeight,
      vh: window.innerHeight, vw: window.innerWidth,
      actions: [...document.querySelectorAll('#aiThread .ai-code-actions .ai-act')].map((b) => ({ t: b.textContent, h: b.getBoundingClientRect().height, r: b.getBoundingClientRect().right })),
      font: getComputedStyle(comp).fontSize,
    };
  });
  ok(m.docOverflow <= 0, name + ': the page does not scroll sideways', String(m.docOverflow));
  ok(m.codeScrollsX, name + ': a long code line scrolls inside the code block');
  ok(m.codeWidth <= m.threadW, name + ': the code block fits the thread', m.codeWidth + ' > ' + m.threadW);
  ok(m.chat.r <= m.vw + 1, name + ': the chat fits the screen width');
  ok(m.actions.length === 5 && m.actions.every((a) => a.r <= m.vw), name + ': the five code actions stay inside the screen');
  if (name === 'phone') {
    ok(m.sideVisible === 'hidden', name + ': the history starts closed');
    ok(parseFloat(m.font) >= 16, name + ': the composer text is 16px or more (no zoom on focus)', m.font);
    ok(m.actions.every((a) => a.h >= 40), name + ': the actions are touch-sized', JSON.stringify(m.actions.map((a) => a.h)));
    ok(m.send.w >= 36 && m.send.h >= 36, name + ': Send is touch-sized');
    await page.click('.ai-open-list');
    ok(await page.evaluate(() => getComputedStyle(document.getElementById('aiSidebar')).visibility) === 'visible', name + ': the drawer opens');
    ok(await page.evaluate(() => { const b = document.querySelector('.ai-backdrop'); return getComputedStyle(b).display === 'block'; }), name + ': a backdrop covers the chat');
    if (process.env.SHOTS) await page.screenshot({ path: path.join(process.env.SHOTS, 'phone-drawer.png') });
    await page.keyboard.press('Escape');
    await page.waitForTimeout(300);
    ok(await page.evaluate(() => getComputedStyle(document.getElementById('aiSidebar')).visibility) === 'hidden', name + ': Escape closes the drawer');
    await page.click('.ai-open-list');
    await page.click('#aiConvs .ai-conv-title >> nth=1');
    await page.waitForTimeout(300);
    ok(await page.evaluate(() => document.getElementById('aiMainTitle').textContent.includes('number 1')), name + ': choosing a chat opens it');
    ok(await page.evaluate(() => getComputedStyle(document.getElementById('aiSidebar')).visibility) === 'hidden', name + ': and closes the drawer');
  } else {
    ok(m.sideVisible === 'visible' && m.side.w > 150, name + ': the history is visible', JSON.stringify(m.side));
    if (name === 'desktop') {
      const col = await page.evaluate(() => { const u = document.querySelector('#aiThread .ai-msg-assistant').getBoundingClientRect(); return u.width; });
      ok(col <= 852, name + ': the reading column is capped near 850px', String(col));
    }
    await page.click('#aiSidebar .ai-sidebar-toggle');
    await page.waitForTimeout(350);
    ok(await page.evaluate(() => getComputedStyle(document.getElementById('aiSidebar')).visibility) === 'hidden', name + ': the history collapses');
    ok(await page.evaluate(() => document.activeElement && document.activeElement.classList.contains('ai-open-list')), name + ': focus moves to the reopen button');
    await page.click('.ai-open-list');
    await page.waitForTimeout(350);
    ok(await page.evaluate(() => getComputedStyle(document.getElementById('aiSidebar')).visibility) === 'visible', name + ': and reopens');
  }
  // the composer is on screen and typing grows it without covering the thread
  await page.fill('#aiComposer', Array.from({ length: 8 }, (_, i) => 'line ' + i).join('\n'));
  const after = await page.evaluate(() => { const c = document.getElementById('aiComposer').getBoundingClientRect(), s = document.getElementById('aiSendBtn').getBoundingClientRect(), t = document.getElementById('aiThread').getBoundingClientRect(); return { cb: c.bottom, sb: s.bottom, tb: t.bottom, ct: c.top, h: c.height, vh: window.innerHeight }; });
  ok(after.h > 60 && after.h <= 242, name + ': the message box grows with the text, up to its cap', String(after.h));
  ok(after.sb <= after.vh + 1 && after.tb <= after.ct + 1, name + ': the composer stays on screen below the thread', JSON.stringify(after));
  // keyboard focus is visible
  await page.focus('#aiComposer');
  const ring = await page.evaluate(() => getComputedStyle(document.querySelector('#sec-nlai .ai-box')).boxShadow);
  ok(/rgba?\(52, 211, 153/.test(ring), name + ': the focused composer has a visible ring', ring);
  if (process.env.SHOTS) await page.screenshot({ path: path.join(process.env.SHOTS, name + '.png') });
  // the welcome screen
  await page.evaluate(() => { aiState.convs = []; aiState.activeId = null; aiChatRender(); });
  ok(await page.evaluate(() => { const e = document.querySelector('#aiThread .ai-empty'); return !!e && e.getBoundingClientRect().right <= window.innerWidth; }), name + ': the welcome screen fits');
  if (process.env.SHOTS) await page.screenshot({ path: path.join(process.env.SHOTS, name + '-welcome.png') });
  ok(problems.length === 0, name + ': no console error or CSP violation', problems.join(' | ').slice(0, 300));
  await ctx.close();
}
await browser.close(); server.close();
console.log(`\n${pass} passed, ${fail} failed`);
process.exit(fail ? 1 : 0);
